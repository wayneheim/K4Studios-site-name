/**
 * Remove 4 deleted images from Color.mjs by ID.
 * Outputs the exact changes needed.
 */
const fs = require('fs');
const path = 'src/data/Galleries/Painterly-Fine-Art-Photography/Facing-History/Western-Cowboy-Portraits/Color.mjs';
const content = fs.readFileSync(path, 'utf8');

const idsToRemove = ['i-tg6PTwd', 'i-pVMMLRp', 'i-GmTkrzR', 'i-bzp2Pxw'];

// Parse as JSON array (strip the export prefix)
const jsonStr = content.replace(/^[^[]*/, '').replace(/;\s*$/, '');
const data = JSON.parse(jsonStr);

const before = data.length;
const filtered = data.filter(item => !idsToRemove.includes(item.id));
const after = filtered.length;

console.log(`Before: ${before} items`);
console.log(`After: ${after} items`);
console.log(`Removed: ${before - after} items`);

// Verify removed ones
const removedIds = data.filter(item => idsToRemove.includes(item.id)).map(i => `${i.id} "${i.title}"`);
console.log('Removed:', removedIds);

// Write back
const output = '// Auto-generated by GalleryOrderer – review & commit\nexport const galleryData = ' + JSON.stringify(filtered, null, 2) + ';\n';
fs.writeFileSync(path, output, 'utf8');
console.log('Written updated file.');
