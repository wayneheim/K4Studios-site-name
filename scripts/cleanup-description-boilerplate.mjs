import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const args = process.argv.slice(2);
const APPLY = args.includes("--apply");
const LIMIT_ARG = args.find((arg) => arg.startsWith("--limit="));
const LIMIT = LIMIT_ARG ? Number.parseInt(LIMIT_ARG.split("=")[1], 10) : Infinity;
const FILE_ARG = args.find((arg) => arg.startsWith("--file="));

const DEFAULT_FILE = path.resolve(
  __dirname,
  "../src/data/Galleries/Painterly-Fine-Art-Photography/Facing-History/Western-Cowboy-Portraits/Color.mjs"
);
const TARGET_FILE = FILE_ARG
  ? path.resolve(process.cwd(), FILE_ARG.split("=").slice(1).join("="))
  : DEFAULT_FILE;

const BOILERPLATE_SENTENCES = [
  "The softened color, period clothing, and measured posture place the work among cowboy portraits shaped by fine art Western photography and painterly Western photography.",
  "It reads as narrative Western art from the American frontier, inviting the viewer to step into the story rather than merely observe the pose.",
  "Soft atmosphere, period detail, and restrained expression place the scene within fine art Western photography and painterly Western photography, grounding her presence in frontier life on the American frontier.",
  "The result is narrative Western art with quiet psychological weight, built less around action than the unanswered story carried in her stance.",
  "The period clothing, weathered setting, and controlled light strengthen its place in fine art Western photography while keeping the mood intimate and human.",
  "This is painterly Western photography rooted in frontier life, carrying the quiet pull of narrative Western art and the American frontier.",
  "Weathered wood, badge, and steady bearing tie the portrait to classic cowboy portraits while preserving the more atmospheric language of painterly Western photography.",
  "The image works as narrative Western art from the American frontier, carrying authority without spectacle.",
  "Softened color, guarded posture, and period equipment place the figure inside fine art Western photography shaped by tension rather than action.",
  "The result is painterly Western photography with the grit of cowboy art and the unresolved edge of Wild West photography.",
];

function parseGalleryData(fileContent) {
  const match = fileContent.match(/export const galleryData = (\[[\s\S]*\]);?\s*$/);
  if (!match) {
    throw new Error("Could not parse galleryData export.");
  }
  return new Function(`return ${match[1]}`)();
}

function normalizeDescriptionWhitespace(value) {
  return String(value)
    .split("\n\n")
    .map((paragraph) =>
      paragraph
        .replace(/[ \t]{2,}/g, " ")
        .replace(/\s+([.,;:!?])/g, "$1")
        .trim()
    )
    .filter(Boolean)
    .join("\n\n");
}

function removeBoilerplateSentences(description) {
  let next = String(description || "");
  const removed = [];

  for (const sentence of BOILERPLATE_SENTENCES) {
    if (!next.includes(sentence)) continue;
    next = next.replaceAll(sentence, "");
    removed.push(sentence);
  }

  return {
    description: normalizeDescriptionWhitespace(next),
    removed,
  };
}

function firstParagraph(value) {
  return String(value || "").split("\n\n")[0].trim();
}

function validateDescription(image, before, after, removed) {
  const issues = [];
  const first = firstParagraph(after);

  if (!first) issues.push("empty first paragraph");
  if (/\b(and|or|but|while|where|with|as)\s*$/i.test(first)) issues.push("dangling connector");
  if (/[,;:]\s*$/.test(first)) issues.push("dangling punctuation");
  if (/\s{2,}/.test(first)) issues.push("double spaces");
  if (/\s+[.,;:!?]/.test(first)) issues.push("space before punctuation");
  if (removed.length && firstParagraph(before) === first) issues.push("no visible first-paragraph change");
  if (/Copyright|©|Â©/.test(before) && !/Copyright|©|Â©/.test(after)) {
    issues.push("copyright block removed");
  }
  if ((image.story || image.alt || image.title) && typeof after !== "string") {
    issues.push("description became non-string");
  }

  return issues;
}

function rebuildFile(galleryData) {
  return `// Auto-generated by GalleryOrderer - review & commit
export const galleryData = ${JSON.stringify(galleryData, null, 2)};
`;
}

const fileContent = readFileSync(TARGET_FILE, "utf8");
const galleryData = parseGalleryData(fileContent);
const changes = [];
const patternCounts = new Map(BOILERPLATE_SENTENCES.map((sentence) => [sentence, 0]));

for (const image of galleryData) {
  if (!image || typeof image.description !== "string") continue;
  if (changes.length >= LIMIT) break;

  const before = image.description;
  const result = removeBoilerplateSentences(before);
  if (!result.removed.length || result.description === before) continue;

  for (const sentence of result.removed) {
    patternCounts.set(sentence, (patternCounts.get(sentence) || 0) + 1);
  }

  changes.push({
    id: image.id,
    title: image.title,
    before,
    after: result.description,
    removed: result.removed,
    issues: validateDescription(image, before, result.description, result.removed),
  });
}

const issueCount = changes.reduce((count, change) => count + change.issues.length, 0);

console.log(`Mode: ${APPLY ? "APPLY" : "DRY RUN"}`);
console.log(`Target: ${path.relative(process.cwd(), TARGET_FILE)}`);
console.log(`Images with description changes: ${changes.length}`);
console.log(`Validation issues: ${issueCount}`);
console.log("");

console.log("Sentence hit counts:");
for (const [sentence, count] of [...patternCounts.entries()].filter(([, count]) => count > 0)) {
  console.log(`- ${count}x ${sentence}`);
}
console.log("");

console.log("Before/after review:");
for (const change of changes) {
  console.log(`\n[${change.id}] ${change.title || "(untitled)"}`);
  console.log(`Removed: ${change.removed.length} sentence(s)`);
  if (change.issues.length) console.log(`Issues: ${change.issues.join("; ")}`);
  console.log(`BEFORE: ${firstParagraph(change.before)}`);
  console.log(`AFTER:  ${firstParagraph(change.after)}`);
}

if (!changes.length) {
  process.exit(0);
}

if (issueCount > 0) {
  console.log("\nRefusing to apply while validation issues exist.");
  process.exit(APPLY ? 1 : 0);
}

if (!APPLY) {
  console.log("\nDry run only. Re-run with --apply to write changes.");
  process.exit(0);
}

for (const change of changes) {
  const image = galleryData.find((entry) => entry?.id === change.id);
  if (image) image.description = change.after;
}

writeFileSync(TARGET_FILE, rebuildFile(galleryData), "utf8");
console.log(`\nApplied ${changes.length} description cleanup(s).`);
