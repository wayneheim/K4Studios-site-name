/**
 * Generates storySliderData.ts from Color.mjs
 * 
 * Extracts only id, title, story for images in storySliderImageIds list.
 * This avoids shipping the full 1.4MB Color.mjs to the client.
 * 
 * Run: node scripts/generate-story-slider-data.cjs
 */

const fs = require('fs');
const path = require('path');

// Import source data (ESM/CJS interop works for .mjs)
const { galleryData } = require('../src/data/Galleries/Painterly-Fine-Art-Photography/Facing-History/Western-Cowboy-Portraits/Color.mjs');

// Read storySlider.ts as text and extract image IDs (can't require .ts directly)
const storySliderTsPath = path.join(__dirname, '../src/data/storySlider.ts');
const storySliderContent = fs.readFileSync(storySliderTsPath, 'utf-8');
const idMatches = storySliderContent.match(/"i-[a-zA-Z0-9]+"/g) || [];
const storySliderImageIds = idMatches.map(id => id.replace(/"/g, ''));

// Filter to only the images we need, with minimal fields
const storySliderData = galleryData
  .filter(img => storySliderImageIds.includes(img.id))
  .map(img => ({
    id: img.id,
    title: img.title,
    story: img.story
  }));

// Generate TypeScript output
const output = `/**
 * Auto-generated by scripts/generate-story-slider-data.cjs
 * Do not edit manually - regenerate with: npm run gen:story-slider
 * 
 * Contains minimal story data for StorySlider component (~15KB vs 1.4MB full gallery)
 */

export const storySliderData = ${JSON.stringify(storySliderData, null, 2)};
`;

const outputPath = path.join(__dirname, '../src/data/storySliderData.ts');
fs.writeFileSync(outputPath, output);

console.log(`✓ Generated storySliderData.ts with ${storySliderData.length} stories`);
