import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import {
  chapterDoorwayFrames,
  chapterDoorwayThemes,
  getChapterDoorwayThemeForPaths,
  normalizeDoorwayPath,
} from "../src/data/chapterDoorwayConfig.mjs";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT = path.resolve(__dirname, "..");
const MASTER_DATA_PATH = path.join(ROOT, "src/data/galleryMaps/MasterGalleryData.mjs");
const OUTPUT_PATH = path.join(ROOT, "src/data/chapterDoorwayAssignments.generated.js");

const HIDDEN_VISIBILITY = new Set(["hidden", "non", "none", ""]);
const GHOST_IMAGE_ID = "i-k4studios";

function isVisibleImage(img) {
  if (!img?.id) return false;
  if (String(img.id).trim().toLowerCase() === GHOST_IMAGE_ID) return false;
  const visibility = String(img.visibility || "show").trim().toLowerCase();
  return !HIDDEN_VISIBILITY.has(visibility);
}

function cleanAssignment(assignment) {
  if (!assignment?.theme || !assignment?.href) return null;
  const theme = chapterDoorwayThemes.find((item) => item.key === assignment.theme);
  if (!theme) return null;

  const href = normalizeDoorwayPath(assignment.href);
  const doorwayPaths = theme.doorwayPaths.map(normalizeDoorwayPath);
  if (!doorwayPaths.includes(href)) return null;

  const frameIndex = Number.isInteger(assignment.frameIndex)
    ? assignment.frameIndex % chapterDoorwayFrames.length
    : doorwayPaths.indexOf(href) % chapterDoorwayFrames.length;

  return {
    theme: theme.key,
    href,
    frameIndex,
  };
}

function buildImageRecords(galleryDataMap) {
  const records = new Map();
  let order = 0;

  for (const [galleryPath, images] of Object.entries(galleryDataMap)) {
    if (!Array.isArray(images)) continue;

    for (const img of images) {
      if (!isVisibleImage(img)) continue;

      const id = String(img.id).trim();
      const normalizedGalleryPath = normalizeDoorwayPath(galleryPath);
      const imgGalleryPaths = Array.isArray(img.galleries)
        ? img.galleries.map(normalizeDoorwayPath)
        : [];
      const paths = [normalizedGalleryPath, ...imgGalleryPaths].filter(Boolean);

      if (!records.has(id)) {
        records.set(id, {
          id,
          order: order++,
          paths: new Set(),
        });
      }

      const record = records.get(id);
      for (const itemPath of paths) {
        record.paths.add(itemPath);
      }
    }
  }

  return Array.from(records.values()).sort((a, b) => a.order - b.order);
}

function makeEmptyCounts() {
  return Object.fromEntries(chapterDoorwayThemes.map((theme) => [theme.key, 0]));
}

function getCursorStart(theme, existingCursors, retainedCounts) {
  const cursor = Number(existingCursors?.[theme.key]);
  if (Number.isInteger(cursor) && cursor >= 0) return cursor;
  return retainedCounts[theme.key] || 0;
}

function serializeGeneratedModule(assignments, cursors, meta) {
  return [
    "// Auto-generated by scripts/generate-chapter-doorway-assignments.mjs.",
    "// Run `npm run gen:chapter-doorway-links` after gallery data changes.",
    `export const chapterDoorwayAssignments = ${JSON.stringify(assignments, null, 2)};`,
    "",
    `export const chapterDoorwayCursors = ${JSON.stringify(cursors, null, 2)};`,
    "",
    `export const chapterDoorwayAssignmentMeta = ${JSON.stringify(meta, null, 2)};`,
    "",
  ].join("\n");
}

async function main() {
  const [{ galleryDataMap }, existingModule] = await Promise.all([
    import(pathToFileURL(MASTER_DATA_PATH).href),
    fs.existsSync(OUTPUT_PATH)
      ? import(`${pathToFileURL(OUTPUT_PATH).href}?t=${Date.now()}`)
      : Promise.resolve({}),
  ]);

  const existingAssignments = existingModule.chapterDoorwayAssignments || {};
  const existingCursors = existingModule.chapterDoorwayCursors || {};
  const records = buildImageRecords(galleryDataMap || {});
  const retainedCounts = makeEmptyCounts();
  const themeCounts = makeEmptyCounts();
  const assignments = {};
  const cursors = {};
  const skipped = {
    noTheme: 0,
    noDoorways: 0,
  };

  for (const record of records) {
    const paths = Array.from(record.paths);
    const theme = getChapterDoorwayThemeForPaths(paths);
    if (!theme) {
      skipped.noTheme++;
      continue;
    }
    if (!theme.doorwayPaths.length) {
      skipped.noDoorways++;
      continue;
    }

    const retained = cleanAssignment(existingAssignments[record.id]);
    if (retained && retained.theme === theme.key) {
      assignments[record.id] = retained;
      retainedCounts[theme.key]++;
      themeCounts[theme.key]++;
    }
  }

  for (const theme of chapterDoorwayThemes) {
    cursors[theme.key] = getCursorStart(theme, existingCursors, retainedCounts);
  }

  for (const record of records) {
    if (assignments[record.id]) continue;

    const theme = getChapterDoorwayThemeForPaths(Array.from(record.paths));
    if (!theme?.doorwayPaths?.length) continue;

    const cursor = cursors[theme.key] || 0;
    const href = normalizeDoorwayPath(theme.doorwayPaths[cursor % theme.doorwayPaths.length]);
    assignments[record.id] = {
      theme: theme.key,
      href,
      frameIndex: cursor % chapterDoorwayFrames.length,
    };
    cursors[theme.key] = cursor + 1;
    themeCounts[theme.key]++;
  }

  const assignedCount = Object.keys(assignments).length;
  const meta = {
    generatedAt: new Date().toISOString(),
    assignedCount,
    themeCounts,
    skipped,
  };

  fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
  fs.writeFileSync(OUTPUT_PATH, serializeGeneratedModule(assignments, cursors, meta));

  console.log(`Generated ${path.relative(ROOT, OUTPUT_PATH)} with ${assignedCount} assignments.`);
  console.log(`Skipped ${skipped.noTheme} visible images without a configured doorway theme.`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
