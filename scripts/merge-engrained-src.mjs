/**
 * Merge srcS, srcM, srcL, srcXL from scrape data into Engrained-Series.mjs
 */

import { galleryData as scrapeData } from '../src/data/Other/Photo-Shoots/Engrained/2026-Engrained-1.mjs';
import { galleryData as targetData } from '../src/data/Other/K4-Select-Series/Engrained/Engrained-Series.mjs';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

// Build lookup from scrape
const scrapeMap = new Map();
scrapeData.forEach(item => {
  if (item.id && item.id !== 'i-k4studios') {
    scrapeMap.set(item.id, item);
  }
});

console.log('Scrape entries:', scrapeMap.size);
console.log('Target entries:', targetData.length);

// Merge data
let updated = 0;
const mergedData = targetData.map(item => {
  if (!item.id || !scrapeMap.has(item.id)) {
    return item;
  }
  
  const scrape = scrapeMap.get(item.id);
  let changed = false;
  const merged = { ...item };
  
  // Update srcXL if missing or empty
  if ((!merged.srcXL || merged.srcXL === '') && scrape.srcXL) {
    merged.srcXL = scrape.srcXL;
    changed = true;
  }
  
  // Update srcL if missing or empty
  if ((!merged.srcL || merged.srcL === '') && scrape.srcL) {
    merged.srcL = scrape.srcL;
    changed = true;
  }
  
  // Update srcM if missing or empty
  if ((!merged.srcM || merged.srcM === '') && scrape.srcM) {
    merged.srcM = scrape.srcM;
    changed = true;
  }
  
  // Update srcS if missing or empty
  if ((!merged.srcS || merged.srcS === '') && scrape.srcS) {
    merged.srcS = scrape.srcS;
    changed = true;
  }
  
  if (changed) {
    updated++;
    console.log(`  Updated: ${item.id} - ${item.title?.substring(0, 40)}`);
  }
  
  return merged;
});

console.log(`\nTotal updated: ${updated}`);

// Write back to file
const targetPath = path.join(__dirname, '../src/data/Other/K4-Select-Series/Engrained/Engrained-Series.mjs');
const fileContent = `// Auto-generated by GalleryOrderer – review & commit
export const galleryData = ${JSON.stringify(mergedData, null, 2)};
`;

fs.writeFileSync(targetPath, fileContent, 'utf8');
console.log(`\n✅ Written to: ${targetPath}`);
