/**
 * Sort Engrained-Series.mjs by sortOrder descending (highest first)
 */

import { galleryData } from '../src/data/Other/K4-Select-Series/Engrained/Engrained-Series.mjs';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

// Sort by sortOrder descending (highest first)
const sorted = [...galleryData].sort((a, b) => {
  // Keep ghost entry at top
  if (a.visibility === 'ghost') return -1;
  if (b.visibility === 'ghost') return 1;
  return (b.sortOrder || 0) - (a.sortOrder || 0);
});

console.log('First 5 entries (highest sortOrder):');
sorted.slice(0, 5).forEach(e => console.log(`  ${e.sortOrder}: ${e.title?.substring(0, 40)}`));

console.log('\nLast 5 entries (lowest sortOrder):');
sorted.slice(-5).forEach(e => console.log(`  ${e.sortOrder}: ${e.title?.substring(0, 40)}`));

// Write back
const targetPath = path.join(__dirname, '../src/data/Other/K4-Select-Series/Engrained/Engrained-Series.mjs');
const content = `// Auto-generated by GalleryOrderer – review & commit
export const galleryData = ${JSON.stringify(sorted, null, 2)};
`;

fs.writeFileSync(targetPath, content, 'utf8');
console.log(`\n✅ Sorted by sortOrder descending`);
console.log(`   Written to: ${targetPath}`);
