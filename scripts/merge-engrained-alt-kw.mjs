/**
 * Merge corrected alt texts and keywords from 2026-Engrained-1.mjs into Engrained-Series.mjs
 */

import { galleryData as scrapeData } from '../src/data/Other/Photo-Shoots/Engrained/2026-Engrained-1.mjs';
import { galleryData as targetData } from '../src/data/Other/K4-Select-Series/Engrained/Engrained-Series.mjs';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

// Build lookup from scrape
const scrapeMap = new Map();
scrapeData.forEach(item => {
  if (item.id && item.id !== 'i-k4studios') {
    scrapeMap.set(item.id, item);
  }
});

console.log('Scrape entries:', scrapeMap.size);
console.log('Target entries:', targetData.length);

// Merge data
let updated = 0;
const mergedData = targetData.map(item => {
  if (!item.id || !scrapeMap.has(item.id)) {
    return item;
  }
  
  const scrape = scrapeMap.get(item.id);
  let changed = false;
  const merged = { ...item };
  
  // Update alt if scrape has a better one (not generic placeholders)
  if (scrape.alt && !scrape.alt.includes('Fine Art Photography') && !scrape.alt.includes('Photographic artwork')) {
    if (merged.alt !== scrape.alt) {
      merged.alt = scrape.alt;
      changed = true;
    }
  }
  
  // Update keywords if scrape has more relevant ones (not just Civil War Heros ride)
  const scrapeKwStr = JSON.stringify(scrape.keywords);
  const targetKwStr = JSON.stringify(merged.keywords);
  if (!scrapeKwStr.includes('"Civil"') && !scrapeKwStr.includes('"War"') && !scrapeKwStr.includes('"Heros"')) {
    if (targetKwStr !== scrapeKwStr) {
      merged.keywords = scrape.keywords;
      changed = true;
    }
  }
  
  if (changed) {
    updated++;
    console.log(`  Updated: ${item.id} - ${item.title?.substring(0, 40)}`);
  }
  
  return merged;
});

console.log(`\nTotal updated: ${updated}`);

// Write back to file
const targetPath = path.join(__dirname, '../src/data/Other/K4-Select-Series/Engrained/Engrained-Series.mjs');
const fileContent = `// Auto-generated by GalleryOrderer – review & commit
export const galleryData = ${JSON.stringify(mergedData, null, 2)};
`;

fs.writeFileSync(targetPath, fileContent, 'utf8');
console.log(`\n✅ Written to: ${targetPath}`);
